begin;
set local plpgsql.check_asserts=on;
do $test$
declare owner_id uuid:=gen_random_uuid(); visitor uuid:=gen_random_uuid();
  post uuid; comment_id uuid; thread uuid:=gen_random_uuid(); more uuid:=gen_random_uuid(); answer uuid:=gen_random_uuid();
  data jsonb; mail_count integer;
begin
  insert into auth.users(id,email,email_confirmed_at,created_at,raw_user_meta_data) values
    (owner_id,owner_id||'@example.invalid',now(),now(),'{"nickname":"같은이름"}'),
    (visitor,visitor||'@example.invalid',now(),now(),'{"nickname":"같은이름"}');
  assert not has_function_privilege('anon','public.mighty_community_change(uuid,uuid,integer,boolean,text,text)','execute');
  assert not has_function_privilege('anon','public.mighty_support_change(uuid,uuid,integer,boolean,text,text)','execute');
  set local role authenticated;
  perform set_config('request.jwt.claims',jsonb_build_object('sub',owner_id)::text,true);
  data:=public.mighty_community_create(gen_random_uuid(),'old heading','old content');
  post:=(data->>'id')::uuid;
  assert data->>'mine'='true' and data->>'revision'='0';
  perform public.mighty_community_change(post,null,0,false,'수정한 제목','수정한 내용');
  begin perform public.mighty_community_change(post,null,0,true,null,null); assert false,'stale post deleted'; exception when raise_exception then null; end;
  assert public.mighty_community_thread(post)->>'title'='수정한 제목';
  perform public.mighty_support_create(thread,'처음 제목','질문');
  perform public.mighty_support_change(thread,thread,0,false,'바뀐 제목','질문 수정');
  perform public.mighty_support_reply(thread,more,'추가 질문');
  begin perform public.mighty_support_change(thread,thread,0,false,'옛 제목','옛 내용'); assert false,'stale inquiry edited'; exception when raise_exception then null; end;
  perform set_config('request.jwt.claims',jsonb_build_object('sub',visitor)::text,true);
  assert public.mighty_community_thread(post)->>'mine'='false';
  begin perform public.mighty_community_change(post,null,1,false,'다른 회원',''); assert false,'cross-owner edit'; exception when raise_exception then null; end;
  begin perform public.mighty_community_change(post,null,1,true,null,null); assert false,'cross-owner delete'; exception when raise_exception then null; end;
  begin perform public.mighty_support_change(thread,thread,1,true,null,null); assert false,'cross-owner private delete'; exception when raise_exception then null; end;
  data:=public.mighty_community_comment(post,gen_random_uuid(),'다른 사람 댓글');
  comment_id:=(data->'comments'->0->>'id')::uuid;
  assert data->'comments'->0->>'mine'='true';
  reset role;
  insert into mighty_private.support_messages(id,thread_id,is_admin,body) values(answer,thread,true,'관리자 답변');
  select count(*) into mail_count from mighty_private.mail_delivery;
  set local role authenticated;
  perform set_config('request.jwt.claims',jsonb_build_object('sub',owner_id)::text,true);
  begin perform public.mighty_support_change(thread,answer,0,false,null,'관리자 사칭'); assert false,'admin edit'; exception when raise_exception then null; end;
  begin perform public.mighty_support_change(thread,answer,0,true,null,null); assert false,'admin reply removed'; exception when raise_exception then null; end;
  begin perform public.mighty_community_change(post,comment_id,0,true,null,null); assert false,'comment of another member removed'; exception when raise_exception then null; end;
  perform public.mighty_community_change(post,null,1,true,null,null);
  assert public.mighty_community_change(post,null,1,true,null,null);
  data:=public.mighty_community_thread(post);
  assert data->>'deleted'='true' and data->>'mine'='false' and data->'comments'->0->>'body'='다른 사람 댓글';
  assert position('수정한 제목' in data::text)=0 and position('수정한 내용' in data::text)=0;
  begin perform public.mighty_community_comment(post,gen_random_uuid(),'closed'); assert false,'reply to deleted post'; exception when invalid_parameter_value then null; end;
  perform public.mighty_support_change(thread,more,0,false,null,'추가 질문 수정');
  perform public.mighty_support_change(thread,thread,1,true,null,null);
  perform public.mighty_support_change(thread,more,1,true,null,null);
  data:=public.mighty_support_thread(thread);
  assert data->>'deleted'='true' and data->>'answered'='true' and data->'messages'->1->>'body'='관리자 답변';
  assert position('질문 수정' in data::text)=0 and position('바뀐 제목' in data::text)=0;
  begin perform public.mighty_support_reply(thread,gen_random_uuid(),'closed'); assert false,'reply to deleted inquiry'; exception when invalid_parameter_value then null; end;
  thread:=gen_random_uuid();
  perform public.mighty_support_create(thread,'단독 문의','혼자');
  perform public.mighty_support_change(thread,thread,0,true,null,null);
  assert not (public.mighty_support_list()->'items' @> jsonb_build_array(jsonb_build_object('id',thread)));
  perform set_config('request.jwt.claims',jsonb_build_object('sub',visitor)::text,true);
  perform public.mighty_community_change(post,comment_id,0,false,null,'내 댓글 수정');
  perform public.mighty_community_change(post,comment_id,1,true,null,null);
  assert not (public.mighty_community_list()->'items' @> jsonb_build_array(jsonb_build_object('id',post)));
  reset role;
  assert (select count(*) from mighty_private.mail_delivery where source_id<>thread)=mail_count;
end;
$test$;
rollback;
