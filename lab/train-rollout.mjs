import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {decide,INPUT_SIZE,ACTION_SIZE,POLICY_SCHEMA} from './policy.js';
import {playEpisode,rngFor} from './game.js';
import {ruleAction} from './rules-agents.js';
import {utility} from './scoring.js';
import * as versions from './version.mjs';

const read = path=>JSON.parse(readFileSync(path,'utf8'));
const hash = model=>createHash('sha256').update(JSON.stringify(model)).digest('hex');
const [mode,reqPath,outPath]=process.argv.slice(2);
if(mode==='schema') {
  console.log(JSON.stringify({input:INPUT_SIZE,actions:ACTION_SIZE,policy:POLICY_SCHEMA,...versions}));
} else if(mode==='hash') {
  console.log(hash(read(reqPath)));
} else if(mode==='publish') {
  const records=read(reqPath);
  const values=Object.fromEntries(Object.entries(records).map(([k,v])=>[k,read(v.file)]));
  writeFileSync(outPath,'// Selected by held-out validation; generated by lab/train.py.\nexport const champions = '+JSON.stringify(values)+';\n');
} else {
  const req=read(reqPath), model=read(req.model);
  const population=read(new URL('../configs/population.json',import.meta.url));
  const archive=req.archives.map(path=>{const m=read(path);return {id:hash(m),act:(v,r)=>decide(m,v,r)};});
  const episodes=[], config=req.config;
  const choose=list=>list[Math.floor(random()*list.length)];
  let random;
  for(let board=0;board<req.episodes;board++) {
    const seed=mode==='validate'?config.validation_seed+board:req.seeds[board];
    random=rngFor(seed+7342);
    const seats=mode==='validate'?[0,1,2,3,4]:[req.focalSeats[board]];
    const bg=Array.from({length:5},(_,j)=>{
      if(mode==='validate') {
        const id=population.selection_backgrounds[(j+board)%5];
        return {id,act:(v,r)=>ruleAction(id,v,r)};
      }
      if(archive.length && random()<population.history_probability)return choose(archive);
      const id=choose(population.rules);
      return {id,act:(v,r)=>ruleAction(id,v,r)};
    });
    for(const seat of seats) {
      const rows=[];
      const policies=bg.map(a=>a.act);
      const record=g=>{
        const {choices,state,features,priors,teacher,index,logp,value}=g;
        rows.push({state,features,priors,teacher,index,logp,value,legal:choices});
      };
      policies[seat]=(v,r)=>decide(model,v,r,mode==='collect'?record:undefined);
      const result=playEpisode({seed,firstSeat:seed%5,policies});
      const outcome=result.outcomes[seat];
      const reward=utility(req.objective,outcome,{alpha:config.alpha,lambdaRisk:config.lambdaRisk});
      if(!Number.isFinite(reward)) throw Error('Invalid terminal utility');
      episodes.push({seed,seat,opponents:bg.map((b,j)=>j===seat?'focal':b.id),
        reward,win:outcome.win,settlement:outcome.settlement,redeals:result.redealCount,
        ...(mode==='collect'?{rows}:{})});
    }
  }
  writeFileSync(outPath,JSON.stringify(episodes));
}
